"""Saved test-set metric comparisons and evaluation plots."""

import pandas as pd
import streamlit as st

from dashboard_utils import QC_REPORTS, SMART_REPORTS, load_metrics

METRICS = ["accuracy", "precision", "recall", "f1", "roc_auc"]
SMART_NAMES = {
    "logistic_regression": "Logistic Regression",
    "random_forest": "Random Forest",
    "xgboost": "XGBoost",
}
QC_NAMES = {"custom_cnn": "Custom CNN", "mobilenet_v2": "MobileNetV2"}


def _comparison(metrics, names, title):
    rows = []
    for key, label in names.items():
        test = metrics.get(key, {}).get("test", {})
        rows.append({"Model": label, **{metric.upper().replace("_", "-"): test.get(metric) for metric in METRICS}})
    frame = pd.DataFrame(rows).set_index("Model")
    st.subheader(title)
    st.dataframe(frame.style.format("{:.3f}", na_rep="N/A"), width="stretch")
    available = [column for column in frame.columns if frame[column].notna().any()]
    if available:
        st.bar_chart(frame[available], height=300)


def render_performance_page():
    st.title("Model Performance")
    st.write("All values below are loaded from the saved evaluation reports; no metrics are generated by the dashboard.")
    try:
        smart = load_metrics(str(SMART_REPORTS / "metrics.json"))
        quality = load_metrics(str(QC_REPORTS / "metrics.json"))
    except (FileNotFoundError, ValueError) as error:
        st.error(f"Saved evaluation reports could not be loaded: {error}")
        return

    _comparison(smart, SMART_NAMES, "Smart Manufacturing | held-out test split")
    smart_plots = st.columns(2)
    for column, filename, caption in zip(
        smart_plots,
        ["model_comparison.png", "confusion_matrices.png"],
        ["Saved machine model comparison", "Saved machine confusion matrices"],
    ):
        path = SMART_REPORTS / filename
        if path.is_file():
            column.image(str(path), caption=caption, width="stretch")
    roc = SMART_REPORTS / "roc_curves.png"
    if roc.is_file():
        st.image(str(roc), caption="Smart Manufacturing ROC curves", width="stretch")

    st.divider()
    _comparison(quality, QC_NAMES, "Tablet Quality Control | held-out test split")
    quality_plots = st.columns(2)
    for column, filename, caption in zip(
        quality_plots,
        ["model_comparison.png", "confusion_matrices.png"],
        ["Saved tablet model comparison", "Saved tablet confusion matrices"],
    ):
        path = QC_REPORTS / filename
        if path.is_file():
            column.image(str(path), caption=caption, width="stretch")
    roc = QC_REPORTS / "roc_curves.png"
    if roc.is_file():
        st.image(str(roc), caption="Tablet classifier ROC curves", width="stretch")

    history_cols = st.columns(2)
    for column, filename, caption in zip(
        history_cols,
        ["custom_cnn_training_history.png", "mobilenet_v2_training_history.png"],
        ["Custom CNN training history", "MobileNetV2 training history"],
    ):
        path = QC_REPORTS / filename
        if path.is_file():
            column.image(str(path), caption=caption, width="stretch")

    st.caption(
        "ROC-AUC evaluates score ranking independently of a selected class threshold. "
        "The tablet test split contains 200 images; results may not generalize to other cameras, "
        "lighting, tablet products, or production lines."
    )
